const DICTS: Record<Lang, Dict> = { en, pt };

export function t(lang: Lang, key: Key, vars: Record<string, string | number> = {}): string {
  const s = DICTS[lang][key] ?? en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

export const modeLabel = (lang: Lang, m: Mode) => t(lang, `mode.${m}` as Key);

export const DEFAULT_CONTEXT_EN: Record<ContextKey, string> = { work: 'Work', home: 'Home', errand: 'Errands', self: 'Me time' };
export function contextName(lang: Lang, key: ContextKey, custom: Record<ContextKey, string>): string {
  const c = custom[key];
  return !c || c === DEFAULT_CONTEXT_EN[key] ? t(lang, `ctx.${key}` as Key) : c;
}
